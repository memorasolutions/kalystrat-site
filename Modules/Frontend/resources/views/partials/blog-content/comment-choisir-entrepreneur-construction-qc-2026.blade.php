<h2 id="recours">Recours en cas de litige (RBQ, GCR, OPC, tribunaux)</h2>
<p>Même avec une sélection rigoureuse, des problèmes peuvent survenir. Plusieurs recours existent, selon la nature du projet et du litige. Le choix du bon canal dépend entièrement du contexte&nbsp;: résidentiel neuf, rénovation, achat usagé, non-paiement, etc.</p>
<p>Pour une <strong>maison neuve couverte par la garantie GCR</strong>, la première étape est d’ouvrir un dossier de réclamation directement auprès de GCR via son site web. Cette démarche active la couverture du plan de garantie. Parallèlement, toute infraction à la réglementation de la RBQ (licence invalide, sous-catégorie incorrecte) peut faire l’objet d’une plainte formelle à la Régie du bâtiment du Québec.</p>
<p>Pour les <strong>projets de rénovation</strong> ou d’<strong>achat de maison usagée</strong>, l’Office de la protection du consommateur (OPC) est l’interlocuteur principal en cas de manquement contractuel ou de pratique commerciale déloyale. L’OPC peut offrir de l’information et orienter vers une médiation ou une plainte formelle.</p>
<p>Si un <strong>entrepreneur opère sans licence</strong>, une plainte à la RBQ est la démarche appropriée. En cas de <strong>non-paiement</strong> d’un sous-traitant ou d’un fournisseur, celui-ci peut inscrire une hypothèque légale sur la propriété dans les 30 jours suivant la fin des travaux, puis intenter une action en justice. Pour un <strong>vice caché</strong> sur un immeuble usagé non couvert par GCR, le recours se fonde sur l’article 1726 du Code civil du Québec et se traite devant les tribunaux civils. Enfin, le Tribunal administratif du logement (TAL) n’intervient que dans les litiges locatifs (bail) et n’a aucune compétence en matière de construction pour un propriétaire.</p>

