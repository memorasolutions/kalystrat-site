<h2 id="faq">Questions fréquentes</h2>

<h3>Comment vérifier la licence RBQ d’un entrepreneur&nbsp;?</h3>
<p>Rendez-vous sur le site officiel de la Régie du bâtiment du Québec (<a href="https://www.rbq.gouv.qc.ca" target="_blank" rel="noopener">rbq.gouv.qc.ca</a>) et utilisez l’outil «&nbsp;Vérifier un entrepreneur&nbsp;». Vous y trouverez le statut de la licence, les sous-catégories détenues, les sanctions éventuelles et l’historique des réclamations au cautionnement de licence sur les cinq dernières années.</p>

<h3>Qu’est-ce que la GCR et qui doit y être accrédité&nbsp;?</h3>
<p>La GCR (Garantie de construction résidentielle) administre le plan de garantie obligatoire pour les bâtiments résidentiels neufs assujettis au Québec, sous mandat de la RBQ depuis 2015. Tout entrepreneur qui construit une maison unifamiliale, un plex (duplex à quintuplex) ou une petite copropriété divise visée doit être accrédité auprès de GCR, en plus de détenir la licence RBQ appropriée (1.1.1 ou 1.1.2).</p>

<h3>Quelle sous-catégorie RBQ faut-il pour construire une maison neuve&nbsp;?</h3>
<p>Pour une maison unifamiliale isolée, jumelée ou en rangée, l’entrepreneur doit détenir la sous-catégorie 1.1.1. Pour une copropriété divise de quatre parties privatives superposées ou moins, d’une hauteur maximale de trois étages et d’une superficie au sol maximale de 600 m², c’est la sous-catégorie 1.1.2 qui s’applique.</p>

<h3>Quel acompte maximum verser à la signature du contrat&nbsp;?</h3>
<p>Il est recommandé de ne pas verser plus de 10 % à la signature, sauf si des achats spécifiques de matériaux justifient un montant plus élevé. Pour un condo neuf (copropriété divise), l’acompte doit être entièrement protégé par GCR, assurance, cautionnement ou dépôt en fidéicommis, conformément à la Loi sur le bâtiment.</p>

<h3>Que couvre le plan de garantie GCR sur 1, 3 et 5 ans&nbsp;?</h3>
<p>Le plan GCR couvre&nbsp;: 1 an pour les malfaçons et défauts apparents à la réception (finitions), 3 ans pour les vices cachés (défauts non visibles à la réception), et 5 ans pour les vices majeurs touchant la structure ou l’étanchéité de l’enveloppe (fondations, toiture, murs extérieurs). Les acomptes sont protégés jusqu’à 50 000 $ et la couverture principale atteint jusqu’à 300 000 $ par habitation unifamiliale typique.</p>

<h3>Quels sont mes recours en cas de problème avec mon entrepreneur&nbsp;?</h3>
<p>Pour une maison neuve assujettie, ouvrez d’abord un dossier auprès de GCR. Pour une rénovation, adressez-vous à l’OPC, puis aux tribunaux civils au besoin. Si l’entrepreneur n’a pas de licence, portez plainte à la RBQ. En cas de non-paiement de sous-traitants, une hypothèque légale peut être inscrite dans les 30 jours suivant la fin des travaux. Le Tribunal administratif du logement ne traite pas les litiges de construction pour un propriétaire.</p>

