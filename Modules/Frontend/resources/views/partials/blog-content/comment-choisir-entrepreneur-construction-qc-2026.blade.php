<h2 id="rbq">1. Vérifier la licence RBQ et sa sous-catégorie</h2>
<p>Toute personne qui exécute ou fait exécuter des travaux de construction ou de rénovation au Québec doit détenir une licence délivrée par la Régie du bâtiment du Québec (RBQ), sauf rares exceptions prévues par la Loi sur le bâtiment. Cette obligation s’applique autant aux entrepreneurs généraux qu’aux spécialistes (plombiers, électriciens, etc.). La première étape incontournable consiste à consulter le <strong>registre public gratuit</strong> de la RBQ, accessible à l’adresse <a href="https://www.rbq.gouv.qc.ca" target="_blank" rel="noopener">rbq.gouv.qc.ca</a>, via l’outil «&nbsp;Vérifier un entrepreneur&nbsp;».</p>
<p>Ce registre affiche en temps réel le statut de la licence (active, suspendue, révoquée), la ou les sous-catégories détenues, ainsi que l’historique de sanctions disciplinaires, de plaintes fondées ou de réclamations au cautionnement de licence au cours des cinq dernières années. Il est crucial de s’assurer que la sous-catégorie correspond exactement à la nature du projet envisagé. Par exemple, un entrepreneur détenteur uniquement de la sous-catégorie 1.2 (petits bâtiments) ne peut légalement entreprendre la construction d’un immeuble qui relève de la sous-catégorie 1.3.</p>
<p>Les sous-catégories principales pour un entrepreneur général sont définies à l’annexe 1 du Règlement sur les licences de la RBQ&nbsp;:</p>
<ul>
<li><strong>1.1.1</strong> — Bâtiments résidentiels neufs de classe I&nbsp;: maisons unifamiliales (isolées, jumelées ou en rangée), plex du duplex au quintuplex (non en copropriété divise), certains multifamiliaux à vocation sociale (OBNL ou coopératives).</li>
<li><strong>1.1.2</strong> — Bâtiments résidentiels neufs de classe II&nbsp;: copropriétés divises de quatre parties privatives superposées ou moins, hauteur maximale 3 étages, superficie au sol maximale 600 m².</li>
<li><strong>1.2</strong> — Petits bâtiments visés à la Partie 9 du Code national du bâtiment (CNB), autres que 1.1.1 et 1.1.2.</li>
<li><strong>1.3</strong> — Bâtiments visés à la Partie 3 du CNB, soit généralement de plus de 3 étages ou de plus de 600 m².</li>
</ul>
<p>Il faut aussi distinguer clairement le <strong>cautionnement de licence</strong> du <strong>cautionnement de performance</strong>. Le premier est une garantie financière que tout entrepreneur doit déposer auprès de la RBQ pour obtenir sa licence&nbsp;; en cas de réclamation fondée, la RBQ peut ordonner le versement d’une indemnité à partir de ce cautionnement, et cette information apparaît dans le registre public. Le cautionnement de performance, quant à lui, est une assurance distincte souscrite volontairement par l’entrepreneur auprès d’un assureur&nbsp;: il garantit l’achèvement des travaux si celui-ci fait faillite en cours de chantier.</p>

<h2 id="gcr">2. Garantie GCR&nbsp;: la protection obligatoire pour le résidentiel neuf</h2>
<p>Depuis 2015, la <strong>Garantie de construction résidentielle (GCR)</strong> est l’administrateur du plan de garantie officiel pour les bâtiments résidentiels neufs assujettis au Québec, sous mandat de la RBQ. Ce plan est prévu par le Règlement sur le plan de garantie des bâtiments résidentiels neufs, pris en application de la Loi sur le bâtiment. Il est <strong>légalement obligatoire</strong> pour tout entrepreneur qui construit des habitations neuves couvertes par ce règlement.</p>
<p>Pour être admissible, l’entrepreneur doit cumuler deux conditions&nbsp;: détenir une licence RBQ valide avec la sous-catégorie <strong>1.1.1 ou 1.1.2</strong>, et être accrédité auprès de GCR. Sans cette double condition, le projet n’est pas couvert et l’entrepreneur est en infraction.</p>
<p>Les bâtiments couverts incluent les maisons unifamiliales (isolées, jumelées ou en rangée, incluant les unités intergénérationnelles), les plex allant du duplex au quintuplex (hors copropriété divise), ainsi que les copropriétés divises de quatre parties privatives superposées ou moins. Toute personne envisageant l’achat ou la construction d’une telle habitation doit s’assurer que l’entrepreneur est bien accrédité GCR. Cette information est vérifiable sur <a href="https://www.garantiegcr.com" target="_blank" rel="noopener">garantiegcr.com</a>, où il est possible de consulter le statut d’un entrepreneur et, le cas échéant, le numéro de dossier du plan de garantie.</p>
<p>Le plan GCR offre une protection structurée en trois périodes distinctes. Les <strong>acomptes versés avant la livraison sont protégés jusqu’à 50 000 $</strong>. Pour une maison unifamiliale isolée, jumelée ou en rangée (non en indivision), la <strong>couverture principale atteint jusqu’à 300 000 $ par habitation</strong>. Les plafonds varient pour les copropriétés divises et sont détaillés sur le site de GCR.</p>

